#include "libft.h"

int	ft_isalnum(int alnum)
{
	if ((alnum >= '0' && alnum <= '9')
		|| (alnum >= 'a' && alnum <= 'z')
		|| (alnum >= 'A' && alnum <= 'Z'))
		return (1);
	else
		return (0);
}
